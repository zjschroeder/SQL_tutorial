glossary_matches <- function(e, q, cat) {
  if (!is.null(cat) && nzchar(cat) && cat != "All" && e$cat != cat) return(FALSE)
  if (is.null(q) || !nzchar(trimws(q))) return(TRUE)
  hay <- tolower(paste(e$term, paste(e$also, collapse = " "), e$def, e$ex, e$tsql, e$tab))
  grepl(tolower(trimws(q)), hay, fixed = TRUE)
}

